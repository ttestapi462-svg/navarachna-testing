CREATE TABLE IF NOT EXISTS public.tbl_expenses
(
    id                bigint GENERATED BY DEFAULT AS IDENTITY,
    expense_date      date                      NOT NULL,
    amount            numeric(12,2)             NOT NULL CHECK (amount > 0),
    category_notes    character varying(250)    NOT NULL,
    bill_blob_name    character varying(300)    NOT NULL,
    bill_file_name    character varying(255)    NOT NULL,
    bill_content_type character varying(100)    NOT NULL,

    created_at        timestamp with time zone  NOT NULL DEFAULT clock_timestamp(),
    created_by        bigint,
    updated_at        timestamp with time zone,
    updated_by        bigint,

    is_deleted        boolean                   NOT NULL DEFAULT false,
    deleted_by        bigint,
    deleted_at        timestamp with time zone,

    CONSTRAINT "PK_tbl_expenses" PRIMARY KEY (id),
    CONSTRAINT "FK_tbl_expenses_tbl_users_created_by" FOREIGN KEY (created_by) REFERENCES public.tbl_users (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_tbl_expenses_tbl_users_updated_by" FOREIGN KEY (updated_by) REFERENCES public.tbl_users (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_tbl_expenses_tbl_users_deleted_by" FOREIGN KEY (deleted_by) REFERENCES public.tbl_users (id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_tbl_expenses_date       ON public.tbl_expenses (expense_date);
CREATE INDEX IF NOT EXISTS idx_tbl_expenses_created_by ON public.tbl_expenses (created_by);
